const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const moduleUnderTest = { exports: {} };
new Function('module', 'exports', ts.transpileModule(fs.readFileSync('lib/searchRequestGate.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText)(moduleUnderTest, moduleUnderTest.exports);
const gate = moduleUnderTest.exports.createSearchRequestGate();
const first = gate.begin();
assert.ok(gate.accepts(first));
gate.invalidate();
assert.ok(!gate.accepts(first), 'Typing invalidates old requests before debounce fires');
const next = gate.begin();
assert.ok(gate.accepts(next));
assert.ok(!gate.accepts(first), 'Late responses cannot replace newer results');
const submitted = gate.begin();
assert.ok(!gate.accepts(next), 'Explicit search supersedes a debounced request');
gate.invalidate();
assert.ok(!gate.accepts(submitted), 'Clear/unmount prevents results reappearing');
const source = fs.readFileSync('app/(tabs)/discover.tsx', 'utf8');
assert.ok(source.includes('autoCorrect={false}'));
assert.ok(source.includes('spellCheck={false}'));
assert.ok(source.includes('autoCapitalize="none"'));
assert.ok(source.includes('const q = resultsQuery;'), 'Existing results are not filtered against partially typed text');
const dismiss = source.slice(source.indexOf('const dismissSearchKeyboard ='), source.indexOf('const dismissSearchKeyboard =') + 200);
assert.ok(dismiss.includes('Keyboard.dismiss()'));
assert.ok(!dismiss.includes('setQ('), 'Done preserves query');
assert.ok(source.includes('keyboardShouldPersistTaps="handled"'), 'Result actions work with keyboard visible');
assert.ok(!source.includes('>Done</Text>'), 'No separate Done button');
assert.ok(source.includes('accessibilityLabel="Clear search"'), 'Compact clear control is labelled');
assert.ok(source.includes('accessibilityRole="tab"'), 'Search scopes are accessible text tabs');
console.log('PASS: stale-response guard, query stability, autocorrect disabled, keyboard dismissal preserves search and result taps.');
