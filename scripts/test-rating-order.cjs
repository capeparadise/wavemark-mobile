const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const mod = { exports: {} };
const code = ts.transpileModule(fs.readFileSync('lib/ratingOrder.ts','utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
new Function('module','exports',code)(mod,mod.exports);
const { normalizeRatingOrder, normalizeAdvancedOrder, dropRatingSection, defaultRatingOrder, defaultAdvancedOrder } = mod.exports;
assert.deepEqual(normalizeRatingOrder(null), ['overall','advanced','artwork','notes']);
assert.deepEqual(normalizeAdvancedOrder(null), ['production','vocals','lyrics','replay']);
const legacy = ['artwork','lyrics','overall','notes','replay','production','vocals'];
assert.deepEqual(normalizeRatingOrder(legacy), ['artwork','advanced','overall','notes']);
assert.deepEqual(normalizeAdvancedOrder(legacy), ['lyrics','replay','production','vocals']);
assert.deepEqual(normalizeRatingOrder(['bad','notes','notes']), ['notes','overall','advanced','artwork']);
assert.equal(dropRatingSection([...defaultRatingOrder], 'advanced', 0)[0], 'advanced');
assert.deepEqual(dropRatingSection([...defaultAdvancedOrder], 'replay', 0), ['replay','production','vocals','lyrics']);
assert.equal(dropRatingSection([...defaultAdvancedOrder], 'production', 100)[3], 'production');
assert.equal(dropRatingSection([...defaultAdvancedOrder], 'lyrics', -10)[0], 'lyrics');
assert.deepEqual(dropRatingSection([...defaultRatingOrder], 'overall', NaN), [...defaultRatingOrder]);
assert.deepEqual(defaultRatingOrder,['overall','advanced','artwork','notes']);
assert.deepEqual(normalizeAdvancedOrder(JSON.parse(JSON.stringify(['replay','lyrics','vocals','production']))), ['replay','lyrics','vocals','production']);
const modal=fs.readFileSync('components/RatingModal.tsx','utf8');
assert(modal.includes('normalizeRatingOrder(preferences.order).map'));
assert(modal.includes('normalizeAdvancedOrder(preferences.advancedOrder ?? preferences.order).map'));
assert(modal.includes('notes: noteEditor'));
console.log('PASS: grouped order, internal dragging, flat-order migration, bounds, duplicates and rendering wiring.');
